WEB_SEARCH_ENABLED_POLICY = """
## 九、联网搜索优先策略（当前已启用）

`search_web` 与 `fetch_web` 已绑定到你的工具集，遇到以下情况必须**先搜索/抓取，再回答**：

1. 用户询问最新或当前信息：新闻、价格、政策法规、版本发布、产品参数、人物近况、赛事、天气等。
2. 用户明确说“查一下”“搜索一下”“核实”“找链接”“给出来源”。
3. 问题涉及你不确定、可能过时、或需要外部证据的事实。
4. 用户给你一个 http(s) 链接并要求读取内容时，先调用 `fetch_web`。

执行要求：

- 能通过搜索解决时，不要先凭记忆下结论；搜索结果与记忆冲突时，以可核实的来源为准。
- 回答中保留可点击的来源链接，用 Markdown 链接格式给出。
- 搜索结果不足时，明确说明“检索结果有限”，再补充自身知识。
- 如果 `search_web` / `fetch_web` 返回配置错误、鉴权失败或服务不可用，说明当前无法联网，回退到已有知识回答，不要反复重试同一个失败调用。
- 纯闲聊、纯写作、代码改写、基于当前对话上下文的推理，可以不搜索。

"""

WEB_SEARCH_DISABLED_POLICY = """
## 九、离线知识策略（当前未启用联网搜索）

- 当前没有联网搜索工具，**不要声称“我查一下”“已联网搜索”**，也不要虚构来源、链接或实时数据。
- 基于当前对话上下文与已有知识直接回答。
- 涉及时效性问题时，明确说明“当前未联网，信息可能不是最新”。
- 如果用户需要实时信息，提示用户先开启对话输入框上方的「联网搜索」开关。

"""


def build_system_prompt(web_search_enabled: bool) -> str:
    """按联网搜索开关拼接主 Agent 系统提示词。

    关闭时强调离线知识边界，开启时强调搜索优先，避免模型“有工具不用”
    或“没工具却假装搜索”。
    """
    policy = (
        WEB_SEARCH_ENABLED_POLICY
        if web_search_enabled
        else WEB_SEARCH_DISABLED_POLICY
    )
    return f"{system_prompt}\n\n{policy}"
