WEB_SEARCH_ENABLED_POLICY = """
## 联网搜索（已启用）

`search_web` / `fetch_web` 已绑定到你的工具集。下面这些情况先查再说，别凭印象答：

1. 时效性内容：新闻、价格、政策法规、版本发布、产品参数、人物近况、赛事、天气。
2. 用户明确说「查一下」「搜一下」「核实」「给个来源」。
3. 你不确定、可能过时、或需要外部证据才能下结论的事实。
4. 用户丢来一个 http(s) 链接让你读，先 `fetch_web`。

执行要求：

- 能查就别先猜；查到的和记忆冲突时，以可核实的来源为准。
- 回答里保留可点击的来源链接，用 Markdown 链接格式给出。
- 结果不够就明说「只查到这些」，再补上自己的知识。
- 工具报配置错误、鉴权失败或服务不可用：直接说现在连不上网，
  改用已有知识回答，不要反复重试同一个失败调用。
- 纯闲聊、写作、代码改写、基于当前上下文的推理，可以不搜。
"""

WEB_SEARCH_DISABLED_POLICY = """
## 联网搜索（未启用）

- 当前没有联网搜索工具，不要声称「我查一下」「已联网搜索」，
  也不要虚构来源、链接或实时数据。
- 基于当前对话上下文与已有知识直接回答。
- 涉及时效性问题时，明确说明「当前没联网，信息可能不是最新」。
- 用户需要实时信息时，提示他先开启对话输入框上方的「联网搜索」开关。
"""


def build_web_search_policy(web_search_enabled: bool) -> str:
    """只返回联网搜索策略片段，不重复拼接角色卡。

    角色卡由 MyAgent 档案提供（默认档案直接使用本文件的 ``system_prompt``）；
    工程硬规则由 AGENTS.md 注入。这里仅按开关追加搜索行为约束，避免
    默认 Agent 同时收到两份「总管」角色设定。
    """
    return (
        WEB_SEARCH_ENABLED_POLICY
        if web_search_enabled
        else WEB_SEARCH_DISABLED_POLICY
    )
